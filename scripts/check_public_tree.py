#!/usr/bin/env python3
"""Fail when a release tree contains private paths, media, secrets, or broken links."""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MEDIA = {".mp4", ".mov", ".mkv", ".avi", ".webm", ".wav", ".mp3", ".m4a", ".aiff", ".flac", ".ogg", ".opus"}
PRIVATE = re.compile(
    r"/Users/[^/]+/|~/Documents|reference-library|benchmark-footage|"
    r"HANDOFF\.md|taste-deltas?|original-prompts|"
    # yt-dlp style "Title [VIDEOID].ext" filenames leak source video identity.
    r"\[[A-Za-z0-9_-]{11}\]\.(?:mp4|mkv|webm|mov|m4a)",
    re.IGNORECASE,
)

# Optional git-ignored file with extra private markers (names, IDs) that must
# never appear in the public tree -- kept out of this script so the markers
# themselves are not published. One regex per line; '#' lines are comments.
_LOCAL_MARKERS = Path(__file__).resolve().parent / "private_markers.local"
if _LOCAL_MARKERS.exists():
    _extra = [
        line.strip()
        for line in _LOCAL_MARKERS.read_text().splitlines()
        if line.strip() and not line.strip().startswith("#")
    ]
    if _extra:
        PRIVATE = re.compile(PRIVATE.pattern + "|" + "|".join(_extra), re.IGNORECASE)
SECRETS = re.compile(
    r"(?:sk-[A-Za-z0-9_-]{16,}|ghp_[A-Za-z0-9]{20,}|AIza[0-9A-Za-z_-]{20,}|"
    r"-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----)"
)
LINK = re.compile(r"\[[^\]]*\]\(([^)]+)\)")

# AGENTS.md is the single source of truth for the working contract; the three
# files below are generated byte-for-byte copies (scripts/gen-contract.sh) that
# each CLI reads natively. This replaces the honor-system "EDIT ALL SIBLINGS"
# header: if a copy drifts from AGENTS.md, the build fails here.
CONTRACT_SOURCE = Path("AGENTS.md")
CONTRACT_COPIES = (
    Path("CLAUDE.md"),
    Path("GEMINI.md"),
    Path(".github/copilot-instructions.md"),
)


def _contract_drift() -> list[str]:
    """Report any generated contract copy that diverges from AGENTS.md."""
    problems: list[str] = []
    src = ROOT / CONTRACT_SOURCE
    if not src.is_file():
        return [f"missing contract source: {CONTRACT_SOURCE}"]
    source_text = src.read_text()
    for rel in CONTRACT_COPIES:
        dest = ROOT / rel
        if not dest.is_file():
            problems.append(f"missing contract copy: {rel} (run scripts/gen-contract.sh)")
        elif dest.read_text() != source_text:
            problems.append(
                f"contract drift: {rel} differs from {CONTRACT_SOURCE} "
                f"(run scripts/gen-contract.sh)"
            )
    return problems


def _tracked_paths() -> list[Path] | None:
    """Git-tracked files (the actual release tree), or None outside a repo."""
    try:
        out = subprocess.run(
            ["git", "-C", str(ROOT), "ls-files", "-z"],
            capture_output=True, text=True, check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return [ROOT / name for name in out.stdout.split("\0") if name]


def main() -> int:
    problems: list[str] = _contract_drift()
    tracked = _tracked_paths()
    candidates = tracked if tracked is not None else ROOT.rglob("*")
    tracked_set = set(tracked) if tracked is not None else None
    for path in candidates:
        if ".git" in path.parts or not path.is_file():
            continue
        rel = path.relative_to(ROOT)
        if rel in {
            Path(".gitignore"),
            Path("scripts/check_public_tree.py"),
            Path("scripts/private_markers.local"),
        }:
            continue
        if path.suffix.lower() in MEDIA and not rel.as_posix().startswith(
	"assets/foundation-textures-v1/motion/"
	):
            problems.append(f"media file: {rel}")
            continue
        try:
            text = path.read_text()
        except UnicodeDecodeError:
            continue
        if PRIVATE.search(text):
            problems.append(f"private reference: {rel}")
        if SECRETS.search(text):
            problems.append(f"secret-like value: {rel}")
        if path.suffix == ".md":
            for target in LINK.findall(text):
                clean = target.split("#", 1)[0]
                if not clean or target.startswith(("http://", "https://", "mailto:", "#")):
                    continue
                resolved = (path.parent / clean).resolve()
                if not resolved.exists():
                    problems.append(f"broken link: {rel} -> {target}")
                elif (
                    tracked_set is not None
                    and resolved.is_file()
                    and resolved not in tracked_set
                ):
                    # Target exists locally but does not ship -- dead on clone.
                    problems.append(f"link to untracked file: {rel} -> {target}")
    if problems:
        print("\n".join(sorted(set(problems))))
        return 1
    print("public-tree check passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
